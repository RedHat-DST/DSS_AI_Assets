#!/usr/bin/env bash
# Install LaunchAgent so Sales Nav harvest resumes on every login until DONE.
set -euo pipefail

SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ACCOUNTS=""
OUTPUT=""
TERRITORY_ID=""
PREFIX=""
COUNTRY="Netherlands"
MCP_ROOT="${SALESNAV_MCP_ROOT:-$HOME/mcps/linkedin-sales-navigator}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --accounts) ACCOUNTS="$2"; shift 2 ;;
    --output) OUTPUT="$2"; shift 2 ;;
    --territory-id) TERRITORY_ID="$2"; shift 2 ;;
    --prefix) PREFIX="$2"; shift 2 ;;
    --country) COUNTRY="$2"; shift 2 ;;
    --mcp-root) MCP_ROOT="$2"; shift 2 ;;
    *) echo "Unknown arg: $1" >&2; exit 1 ;;
  esac
done

if [[ -z "$ACCOUNTS" || -z "$OUTPUT" || -z "$TERRITORY_ID" ]]; then
  echo "Required: --accounts --output --territory-id" >&2
  exit 1
fi

if [[ -z "$PREFIX" ]]; then
  PREFIX="$(echo "$TERRITORY_ID" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9]+/_/g; s/^_|_$//g')"
fi

LABEL="com.redhat.salesnav-harvest.$(echo "$TERRITORY_ID" | tr '[:upper:]' '[:lower:]' | tr '_' '-')"
PLIST="$HOME/Library/LaunchAgents/${LABEL}.plist"
WRAPPER="$OUTPUT/run_salesnav_loop_wrapper.sh"
SLUG="$(echo "$TERRITORY_ID" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9]+/_/g; s/^_|_$//g')"
DONE_FILE="$OUTPUT/${SLUG}_salesnav_DONE"

mkdir -p "$OUTPUT" "$HOME/Library/LaunchAgents"

# Preflight first (fail fast)
bash "$SKILL_DIR/scripts/preflight.sh" \
  --accounts "$ACCOUNTS" --output "$OUTPUT" --mcp-root "$MCP_ROOT"

cat > "$WRAPPER" <<EOF
#!/usr/bin/env bash
# Auto-generated by install_login_agent.sh — do not edit by hand.
export PATH="/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:\$PATH"
export HOME="${HOME}"
export SALESNAV_MCP_ROOT="${MCP_ROOT}"
DONE_FILE="${DONE_FILE}"
if [[ -f "\$DONE_FILE" ]]; then
  launchctl bootout "gui/\$(id -u)/${LABEL}" 2>/dev/null || true
  exit 0
fi
exec "${SKILL_DIR}/scripts/run_loop.sh" \\
  --accounts "${ACCOUNTS}" \\
  --output "${OUTPUT}" \\
  --territory-id "${TERRITORY_ID}" \\
  --prefix "${PREFIX}" \\
  --country "${COUNTRY}" \\
  --mcp-root "${MCP_ROOT}"
EOF
chmod +x "$WRAPPER"

cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${LABEL}</string>
  <key>ProgramArguments</key>
  <array>
    <string>${WRAPPER}</string>
  </array>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <false/>
  <key>ThrottleInterval</key>
  <integer>60</integer>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key>
    <string>/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin</string>
    <key>HOME</key>
    <string>${HOME}</string>
    <key>SALESNAV_MCP_ROOT</key>
    <string>${MCP_ROOT}</string>
  </dict>
  <key>StandardOutPath</key>
  <string>${OUTPUT}/salesnav_launchagent.log</string>
  <key>StandardErrorPath</key>
  <string>${OUTPUT}/salesnav_launchagent.log</string>
  <key>WorkingDirectory</key>
  <string>${OUTPUT}</string>
</dict>
</plist>
EOF

launchctl bootout "gui/$(id -u)/${LABEL}" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST" 2>/dev/null || launchctl load -w "$PLIST"

nohup "$WRAPPER" >> "$OUTPUT/salesnav_launchagent_manual.log" 2>&1 &

echo "Installed LaunchAgent: $LABEL"
echo "  Runs at every login until $DONE_FILE exists."
echo "  Progress:   $OUTPUT/${PREFIX}_persona_harvest_progress.json"
echo "  State:      $OUTPUT/${SLUG}_salesnav_state.json"
echo "  Logs:       $OUTPUT/${SLUG}_salesnav_loop.log"
echo "  IMPORTANT: Sign in to Sales Nav in MCP Chrome before/during slots."
echo "Disable: launchctl bootout gui/\$(id -u)/${LABEL}"
echo "Started pipeline in background (pid $!)."
